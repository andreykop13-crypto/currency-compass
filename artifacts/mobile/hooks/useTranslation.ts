export type TKey = keyof typeof strings.ru;

export function useTranslation() {
  const { language } = useAppContext();
  const t = (key: TKey): string => {
    const lang = strings[language] as Record<string, string>;
    return lang[key] ?? (strings.ru as Record<string, string>)[key] ?? key;
  };
  return t;
}
